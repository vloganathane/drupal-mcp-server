#!/usr/bin/env bash
# Bring up a D7 source and D11 target for legacy migration testing.
#
# This harness uses the standard Drupal Migrate model: the D11 target reads the
# D7 source database directly. It is therefore not exercised by the generic
# JSON:API run_migration engine.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
SMOKE_ROOT="${LIVE_SMOKEROOT:-/tmp/drupal-mcp-live-d7d11}"
SOURCE_DIR="${SMOKE_ROOT}/source"
TARGET_DIR="${SMOKE_ROOT}/target"
SOURCE_NAME="drupal-mcp-d7-source"
TARGET_NAME="drupal-mcp-d11-legacy-target"
SOURCE_URL="https://${SOURCE_NAME}.ddev.site"
TARGET_URL="https://${TARGET_NAME}.ddev.site"

require() { command -v "$1" >/dev/null 2>&1 || { echo "Missing: $1" >&2; exit 1; }; }

create_source() {
    echo "==> Creating D7 source site"
    rm -rf "$SOURCE_DIR"
    mkdir -p "$SOURCE_DIR"
    cd "$SOURCE_DIR"
    ddev config --project-type=drupal7 --project-name="$SOURCE_NAME" --php-version=7.4 --docroot=. --auto
    ddev start
    if [ ! -f index.php ]; then
        curl -fsSL https://ftp.drupal.org/files/projects/drupal-7.103.tar.gz -o /tmp/drupal-7.103.tar.gz
        tar -xzf /tmp/drupal-7.103.tar.gz -C "$SOURCE_DIR" --strip-components=1
        rm -f /tmp/drupal-7.103.tar.gz
    fi
    ddev restart
    ddev drush site:install standard \
        --site-name="$SOURCE_NAME" \
        --account-name=admin \
        --account-pass=admin \
        -y
    ddev drush cr
    cd "$REPO_ROOT"
}

seed_source() {
    echo "==> Seeding D7 source"
    SOURCE_TMP="$(mktemp)"
    cat > "$SOURCE_TMP" <<'PHP'
$user = new stdClass();
$user->name = "legacy_editor";
$user->mail = "legacy_editor@example.com";
$user->status = 1;
user_save($user);

$vocab = (object) array("name" => "Departures", "machine_name" => "departures");
taxonomy_vocabulary_save($vocab);

$term = new stdClass();
$term->name = "North";
$term->vid = $vocab->vid;
taxonomy_term_save($term);

$node = new stdClass();
$node->type = "article";
node_object_prepare($node);
$node->title = "Legacy article";
$node->language = LANGUAGE_NONE;
$node->body[LANGUAGE_NONE][0]["value"] = "<p>Legacy D7 body</p>";
$node->body[LANGUAGE_NONE][0]["format"] = "filtered_html";
$node->uid = $user->uid;
node_save($node);
print "Seeded D7 user, taxonomy, article.";
PHP
    (
        cd "$SOURCE_DIR"
        ddev drush php-eval "$(cat "$SOURCE_TMP")"
    )
    rm -f "$SOURCE_TMP"
}

create_target() {
    echo "==> Creating D11 target site"
    rm -rf "$TARGET_DIR"
    mkdir -p "$TARGET_DIR"
    cd "$TARGET_DIR"
    ddev config --project-type=drupal11 --project-name="$TARGET_NAME" --php-version=8.3 --docroot=web --auto
    ddev start
    ddev composer create drupal/recommended-project --prefer-dist --no-interaction
    ddev config --docroot=web --project-name="$TARGET_NAME"
    ddev restart
    ddev drush site:install standard \
        --site-name="$TARGET_NAME" \
        --account-name=admin \
        --account-pass=admin \
        -y
    ddev drush en migrate migrate_plus migrate_tools -y
    ddev drush cr
    cd "$REPO_ROOT"
}

write_env() {
    cat > "${REPO_ROOT}/.env.d7d11" <<EOF
# Generated by scripts/live-migration-d7d11.sh
# Target D11 site for drupal-mcp-server
DRUPAL_BASE_URL=${TARGET_URL}
DRUPAL_BASIC_AUTH_USER=admin
DRUPAL_BASIC_AUTH_PASSWORD=admin
DRUPAL_API_TOKEN=
EOF
    echo "Wrote ${REPO_ROOT}/.env.d7d11"
    echo ""
    echo "Source D7 database credentials from DDEV:"
    echo "  host: ddev-${SOURCE_NAME}-db"
    echo "  database: db"
    echo "  user: db"
    echo "  password: db"
    echo ""
    echo "Use those values in the D11 target's migrate database connection."
}

case "${1:-up}" in
    up)
        require ddev
        require docker
        mkdir -p "$SMOKE_ROOT"
        [ -d "${SOURCE_DIR}/.ddev" ] || create_source
        [ -d "${TARGET_DIR}/.ddev" ] || create_target
        seed_source
        write_env
        ;;
    down)
        for dir in "$SOURCE_DIR" "$TARGET_DIR"; do
            [ -d "${dir}/.ddev" ] && (cd "$dir" && ddev delete -Oy)
        done
        rm -rf "$SMOKE_ROOT"
        rm -f "${REPO_ROOT}/.env.d7d11"
        echo "Removed D7/D11 live sites."
        ;;
    seed)
        require ddev
        seed_source
        ;;
    status)
        for dir in "$SOURCE_DIR" "$TARGET_DIR"; do
            if [ -d "${dir}/.ddev" ]; then
                echo "=== ${dir} ==="
                (cd "$dir" && ddev status)
            else
                echo "${dir}: not created"
            fi
        done
        ;;
    *)
        echo "Usage: $0 {up|down|seed|status}" >&2
        exit 1
        ;;
esac
