#!/usr/bin/env bash
# Bring up a D7 source and D11 target for legacy migration testing.
#
# This harness uses the standard Drupal Migrate model: the D11 target reads the
# D7 source database directly. It is therefore not exercised by the generic
# JSON:API run_migration engine.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
SMOKE_ROOT="${LIVE_SMOKEROOT:-/tmp/drupal-mcp-live-d7d11}"
SOURCE_DIR="${SMOKE_ROOT}/source"
TARGET_DIR="${SMOKE_ROOT}/target"
SOURCE_NAME="drupal-mcp-d7-source"
TARGET_NAME="drupal-mcp-d11-legacy-target"
SOURCE_URL="https://${SOURCE_NAME}.ddev.site"
TARGET_URL="https://${TARGET_NAME}.ddev.site"

require() { command -v "$1" >/dev/null 2>&1 || { echo "Missing: $1" >&2; exit 1; }; }

create_source() {
    echo "==> Creating D7 source site"
    rm -rf "$SOURCE_DIR"
    mkdir -p "$SOURCE_DIR"
    cd "$SOURCE_DIR"
    ddev config --project-type=drupal7 --project-name="$SOURCE_NAME" --php-version=7.4 --docroot=. --auto
    ddev start
    if [ ! -f index.php ]; then
        curl -fsSL https://ftp.drupal.org/files/projects/drupal-7.103.tar.gz -o /tmp/drupal-7.103.tar.gz
        tar -xzf /tmp/drupal-7.103.tar.gz -C "$SOURCE_DIR" --strip-components=1
        rm -f /tmp/drupal-7.103.tar.gz
    fi
    ddev restart
    ddev drush site:install standard \
        --site-name="$SOURCE_NAME" \
        --account-name=admin \
        --account-pass=admin \
        -y
    ddev drush cc all
    cd "$REPO_ROOT"
}

seed_source() {
    echo "==> Seeding D7 source"
    local seed_file
    seed_file="$(mktemp)"
    cat > "$seed_file" <<'PHP'
<?php
$user = new stdClass();
$user->name = "legacy_editor";
$user->mail = "legacy_editor@example.com";
$user->status = 1;
user_save($user);

$vocab = (object) array("name" => "Departures", "machine_name" => "departures");
taxonomy_vocabulary_save($vocab);

$term = new stdClass();
$term->name = "North";
$term->vid = $vocab->vid;
taxonomy_term_save($term);

$node = new stdClass();
$node->type = "article";
node_object_prepare($node);
$node->title = "Legacy article";
$node->language = LANGUAGE_NONE;
$node->body[LANGUAGE_NONE][0]["value"] = "<p>Legacy D7 body</p>";
$node->body[LANGUAGE_NONE][0]["format"] = "filtered_html";
$node->uid = $user->uid;
node_save($node);
print "Seeded D7 user, taxonomy, article.\n";
PHP
    (
        cd "$SOURCE_DIR"
        cp "$seed_file" .ddev/seed-migration.php
        ddev drush php-script .ddev/seed-migration.php
    )
    rm -f "$seed_file"
}

create_target() {
    echo "==> Creating D11 target site"
    rm -rf "$TARGET_DIR"
    mkdir -p "$TARGET_DIR"
    cd "$TARGET_DIR"
    ddev config --project-type=drupal11 --project-name="$TARGET_NAME" --php-version=8.3 --docroot=web --auto
    ddev start
    ddev composer create drupal/recommended-project --prefer-dist --no-interaction
    ddev composer require drush/drush --no-interaction
    ddev config --docroot=web --project-name="$TARGET_NAME"
    ddev restart
    ddev drush site:install standard \
        --site-name="$TARGET_NAME" \
        --account-name=admin \
        --account-pass=admin \
        -y
    ddev composer require drupal/migrate_tools drupal/migrate_plus --no-interaction
    ddev drush en migrate migrate_drupal migrate_plus migrate_tools -y
    ddev drush cr
    cd "$REPO_ROOT"
}

write_env() {
    cat > "${REPO_ROOT}/.env.d7d11" <<EOF
# Generated by scripts/live-migration-d7d11.sh
# Target D11 site for drupal-mcp-server
DRUPAL_BASE_URL=${TARGET_URL}
DRUPAL_USERNAME=admin
DRUPAL_PASSWORD=admin
DRUPAL_API_TOKEN=
EOF
    echo "Wrote ${REPO_ROOT}/.env.d7d11"
    echo ""
    echo "Source D7 database credentials from DDEV:"
    echo "  host: ddev-${SOURCE_NAME}-db"
    echo "  database: db"
    echo "  user: db"
    echo "  password: db"
    echo ""
    echo "Use those values in the D11 target's migrate database connection."
}

# Core's d7_* sources read $databases['migrate'] (SqlBase' default key when a
# source declares none), so the target needs that connection plus the
# settings.php hook that loads settings.local.php.
configure_migrate_connection() {
    local settings_dir="${TARGET_DIR}/web/sites/default"
    cat > "${settings_dir}/settings.local.php" <<'PHP'
<?php

/**
 * @file
 * Local overrides for the D11 legacy-migration target.
 *
 * Provides the 'migrate' database connection that core's d7_* migration
 * sources read: SqlBase defaults to the connection named 'migrate' when a
 * source plugin declares no 'key'.
 */

$databases['migrate']['default'] = [
  'driver' => 'mysql',
  'host' => 'ddev-drupal-mcp-d7-source-db',
  'port' => '3306',
  'database' => 'db',
  'username' => 'db',
  'password' => 'db',
];
PHP
    # Uncomment core's settings.local.php include (commented out in the
    # standard template). perl -pi behaves identically on macOS and Linux.
    perl -pi -e '
        s{^# (if \(file_exists\(\$app_root \. .\/. \$site_path \. ./settings\.local\.php.\)\) \{)}{$1};
        s{^#   (include \$app_root \. .\/. \$site_path \. ./settings\.local\.php.;)}{$1};
        s{^# (\})$}{$1} if $seen_include;
        $seen_include = 1 if /^if \(file_exists\(\$app_root/;
    ' "${settings_dir}/settings.php"
}

# Dependency-ordered import for the seeded content: formats first (body format
# lookup), then users, the article bundle, and finally taxonomy.
run_migrations() {
    local step
    for step in d7_filter_format d7_user_role d7_user d7_node_type \
                "d7_node:article" d7_taxonomy_vocabulary \
                "d7_taxonomy_term:departures"; do
        echo "==> migrate:import ${step}"
        (cd "$TARGET_DIR" && ddev drush migrate:import "${step}" -y)
    done
}

verify_migrations() {
    cd "$TARGET_DIR"
    echo "==> Migration status"
    ddev drush migrate:status --format=json 2>/dev/null | python3 -c '
import json, sys
rows = json.load(sys.stdin)
wanted = [
    "d7_filter_format", "d7_user_role", "d7_user", "d7_node_type",
    "d7_node:article", "d7_taxonomy_vocabulary",
    "d7_taxonomy_term:departures",
]
bad = 0
for row in rows:
    if row["id"] in wanted:
        ok = row["imported"] == row["total"] and row["status"] == "Idle"
        bad += 0 if ok else 1
        print("  %-32s %-6s %s/%s" % (row["id"], row["status"], row["imported"], row["total"]))
sys.exit(bad)
'
    echo "==> Migrated content"
    ddev drush sqlq "SELECT n.nid, n.title, u.name AS author, n.status FROM node_field_data n LEFT JOIN users_field_data u ON u.uid = n.uid"
    ddev drush sqlq "SELECT entity_id, body_value, body_format FROM node__body"
    ddev drush sqlq "SELECT tid, name, vid FROM taxonomy_term_field_data"
}

case "${1:-up}" in
    up)
        require ddev
        require docker
        mkdir -p "$SMOKE_ROOT"
        [ -d "${SOURCE_DIR}/.ddev" ] || create_source
        [ -d "${TARGET_DIR}/.ddev" ] || create_target
        seed_source
        write_env
        ;;
    down)
        for dir in "$SOURCE_DIR" "$TARGET_DIR"; do
            [ -d "${dir}/.ddev" ] && (cd "$dir" && ddev delete -Oy)
        done
        rm -rf "$SMOKE_ROOT"
        rm -f "${REPO_ROOT}/.env.d7d11"
        echo "Removed D7/D11 live sites."
        ;;
    seed)
        require ddev
        seed_source
        ;;
    migrate)
        require ddev
        configure_migrate_connection
        run_migrations
        verify_migrations
        ;;
    status)
        for dir in "$SOURCE_DIR" "$TARGET_DIR"; do
            if [ -d "${dir}/.ddev" ]; then
                echo "=== ${dir} ==="
                (cd "$dir" && ddev status)
            else
                echo "${dir}: not created"
            fi
        done
        ;;
    *)
        echo "Usage: $0 {up|down|seed|migrate|status}" >&2
        exit 1
        ;;
esac
