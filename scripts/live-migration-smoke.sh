#!/usr/bin/env bash
# Bring up two DDEV-based Drupal sites for live migration smoke testing.
#
# Usage:
#   scripts/live-migration-smoke.sh up
#   scripts/live-migration-smoke.sh down
#   scripts/live-migration-smoke.sh seed
#   scripts/live-migration-smoke.sh status
#
# The sites are created outside the repository by default. Override the parent
# directory with LIVE_SMOKEROOT=/path/to/dir.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
SMOKE_ROOT="${LIVE_SMOKEROOT:-/tmp/drupal-mcp-live-smoke}"
SOURCE_DIR="${SMOKE_ROOT}/source"
TARGET_DIR="${SMOKE_ROOT}/target"
SOURCE_NAME="drupal-mcp-source"
TARGET_NAME="drupal-mcp-target"
SOURCE_URL="https://${SOURCE_NAME}.ddev.site"
TARGET_URL="https://${TARGET_NAME}.ddev.site"

require() {
    if ! command -v "$1" >/dev/null 2>&1; then
        echo "Missing required command: $1" >&2
        exit 1
    fi
}

run_ddev() {
    local project_dir="$1"
    shift
    (
        cd "$project_dir"
        ddev "$@"
    )
}

create_site() {
    local name="$1"
    local directory="$2"
    echo "==> Creating DDEV site: ${name}"
    rm -rf "$directory"
    mkdir -p "$directory"
    cd "$directory"
    ddev config --project-type=drupal10 --project-name="$name" --php-version=8.3 --docroot=web --auto
    ddev start
    ddev composer create drupal/recommended-project --prefer-dist --no-interaction
    ddev config --docroot=web --project-name="$name"
    ddev restart
    ddev drush site:install standard \
        --site-name="$name" \
        --account-name=admin \
        --account-pass=admin \
        -y
    ddev drush en jsonapi -y
    ddev drush cr
    cd "$REPO_ROOT"
}

seed_source() {
    echo "==> Seeding source site"
    run_ddev "$SOURCE_DIR" exec drush php-eval '
    $user = \\Drupal\\user\\Entity\\User::create([
      "name" => "migration_user",
      "mail" => "migration_user@example.com",
      "status" => 1,
    ]);
    $user->save();

    $vocab = \\Drupal\\taxonomy\\Entity\\Vocabulary::create([
      "vid" => "smoke_vocab",
      "name" => "Smoke vocabulary",
    ]);
    $vocab->save();

    $term = \\Drupal\\taxonomy\\Entity\\Term::create([
      "vid" => "smoke_vocab",
      "name" => "Smoke term",
    ]);
    $term->save();

    $node = \\Drupal\\node\\Entity\\Node::create([
      "type" => "article",
      "title" => "Migration smoke node",
      "body" => [
        "value" => "<p>Source content for migration smoke testing.</p>",
        "format" => "basic_html",
      ],
      "uid" => $user->id(),
    ]);
    $node->save();
    print "Seeded user, taxonomy and node.\\n";
    '
}

write_env() {
    cat > "${REPO_ROOT}/.env.live-smoke" <<EOF
# Generated by scripts/live-migration-smoke.sh
# Target site for drupal-mcp-server
DRUPAL_BASE_URL=${TARGET_URL}
DRUPAL_BASIC_AUTH_USER=admin
DRUPAL_BASIC_AUTH_PASSWORD=admin
DRUPAL_API_TOKEN=
EOF
    echo "Wrote ${REPO_ROOT}/.env.live-smoke"
}

case "${1:-up}" in
    up)
        require ddev
        require docker
        mkdir -p "$SMOKE_ROOT"
        if [ ! -d "${SOURCE_DIR}/.ddev" ]; then
            create_site "$SOURCE_NAME" "$SOURCE_DIR"
        else
            echo "Source site already exists: ${SOURCE_DIR}"
        fi
        if [ ! -d "${TARGET_DIR}/.ddev" ]; then
            create_site "$TARGET_NAME" "$TARGET_DIR"
        else
            echo "Target site already exists: ${TARGET_DIR}"
        fi
        seed_source
        write_env
        echo ""
        echo "Live migration smoke sites are ready:"
        echo "  Source: ${SOURCE_URL}"
        echo "  Target: ${TARGET_URL}"
        echo "  Credentials: admin / admin"
        echo "  Live MCP env: ${REPO_ROOT}/.env.live-smoke"
        ;;
    down)
        for dir in "$SOURCE_DIR" "$TARGET_DIR"; do
            if [ -d "${dir}/.ddev" ]; then
                (
                    cd "$dir"
                    ddev delete -Oy
                )
            fi
        done
        rm -rf "$SMOKE_ROOT"
        rm -f "${REPO_ROOT}/.env.live-smoke"
        echo "Removed live migration smoke sites."
        ;;
    seed)
        require ddev
        seed_source
        ;;
    status)
        for dir in "$SOURCE_DIR" "$TARGET_DIR"; do
            if [ -d "${dir}/.ddev" ]; then
                echo "=== ${dir} ==="
                (cd "$dir" && ddev status)
            else
                echo "${dir}: not created"
            fi
        done
        ;;
    *)
        echo "Usage: $0 {up|down|seed|status}" >&2
        exit 1
        ;;
esac